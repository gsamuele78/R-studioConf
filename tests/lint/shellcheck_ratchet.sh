#!/usr/bin/env bash
# tests/lint/shellcheck_ratchet.sh
set -euo pipefail
# ==============================================================================
# ShellCheck at severity WARNING (Infra-Iam-PKI level: `shellcheck -x -S warning`)
# with a ratchet: findings that already existed when the gate was introduced are
# listed in tests/lint/shellcheck-baseline.txt as "<file> <SCcode> <count>".
#   - a NEW (file, code) pair, or a higher count, fails the gate;
#   - fewer findings than the baseline passes and asks you to shrink it
#     (`make shellcheck-baseline`), so the baseline can only go down.
# Severity ERROR has no baseline: any error fails.
# archive/ is excluded (quarantined, never deployed — see `make clean-archive`).
#
# Usage: tests/lint/shellcheck_ratchet.sh [--update]
# ==============================================================================
RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; NC='\033[0m'

cd "$(dirname "$0")/../.."
BASELINE="tests/lint/shellcheck-baseline.txt"

command -v shellcheck >/dev/null 2>&1 || { echo -e "${RED}shellcheck not installed${NC}" >&2; exit 2; }

mapfile -t FILES < <({ git ls-files '*.sh'; git ls-files init.sh r_env_manager.sh; } | grep -v '^archive/' | sort -u)

# Errors: zero tolerance.
if ! shellcheck -x -S error "${FILES[@]}"; then
    echo -e "${RED}[shellcheck] FAIL — severity error findings (no baseline for errors)${NC}" >&2
    exit 1
fi

current="$(mktemp)"; trap 'rm -f "$current"' EXIT
# gcc format: file:line:col: severity: message [SCxxxx]
{ shellcheck -x -S warning -f gcc "${FILES[@]}" || true; } \
    | sed -nE 's/^([^:]+):[0-9]+:[0-9]+: [a-z]+: .*\[(SC[0-9]+)\]$/\1 \2/p' \
    | sort | uniq -c | awk '{print $2, $3, $1}' >"$current"

if [[ "${1:-}" == "--update" ]]; then
    { echo "# ShellCheck -S warning ratchet baseline — generated by tests/lint/shellcheck_ratchet.sh --update"
      echo "# <file> <SCcode> <count>. Only ever shrink this file."
      cat "$current"; } >"$BASELINE"
    echo -e "${GREEN}[shellcheck] baseline written: $(awk '{s+=$3} END{print s+0}' "$current") findings${NC}"
    exit 0
fi

[[ -f "$BASELINE" ]] || { echo -e "${RED}missing $BASELINE (run with --update once)${NC}" >&2; exit 2; }

status=0
while read -r file code count; do
    allowed="$(awk -v f="$file" -v c="$code" '$1==f && $2==c {print $3}' "$BASELINE")"
    if [[ -z "$allowed" ]]; then
        echo -e "${RED}NEW   ${file} ${code} (${count})${NC}"; status=1
    elif (( count > allowed )); then
        echo -e "${RED}MORE  ${file} ${code} (${count} > baseline ${allowed})${NC}"; status=1
    fi
done <"$current"

total_now="$(awk '{s+=$3} END{print s+0}' "$current")"
total_base="$(grep -v '^#' "$BASELINE" | awk '{s+=$3} END{print s+0}')"
if (( status != 0 )); then
    echo -e "${RED}[shellcheck] FAIL — new warnings above the baseline. Show them with: shellcheck -x -S warning <file>${NC}" >&2
    exit 1
fi
if (( total_now < total_base )); then
    echo -e "${YELLOW}[shellcheck] PASS — ${total_now} warnings, baseline ${total_base}: shrink it with 'make shellcheck-baseline'${NC}"
else
    echo -e "${GREEN}[shellcheck] PASS — ${total_now} warnings (baseline ${total_base}), 0 errors${NC}"
fi
